package String_In_Java;
import java.util.*;

public class charAt_And_length {
    public static void main(String[] args) {
        String s = "satish dadas";
//        int length = s.length();
        System.out.println(s.length()); //12
        System.out.println(s.charAt(4)); //s
        char ch = s.charAt(1);
        System.out.println(ch); //a
    }
}
